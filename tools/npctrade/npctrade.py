"""In-game (NPC) trades: show them, check them, and rebuild the game files from JSON.

    python3 tools/npctrade/npctrade.py show                    # every trade, with nature/gender/ability
    python3 tools/npctrade/npctrade.py show NPC_TRADE_IRON_BELDUM
    python3 tools/npctrade/npctrade.py check                   # do the files agree with the JSON?
    python3 tools/npctrade/npctrade.py build                   # JSON -> the three game files
    python3 tools/npctrade/npctrade.py pid SPECIES_ONIX --nature NATURE_ADAMANT \\
        --gender male --ability 1 --ot-id 48926                 # a personality value to use

The game reads a trade from three places, all generated by `build` from
data/npc_trades.json:
  files/a/1/1/2                         NARC, one 84-byte NPCTrade struct per trade
  files/msgdata/msg/msg_0200.json       nicknames (0..N-1), then OT names (N..2N-1)
  include/constants/npc_trade.h         the NpcTradeNum enum (NPC_TRADE_*), N = NPC_TRADE_MAX
On unmodified data the output is byte-identical to the retail files.
`dump` writes the JSON from the current game files (to start over).
docs/modding/gift-pokemon-and-trades.md explains the fields and the scripts.
"""

import argparse
import json
import os
import re
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
JSON_PATH = "data/npc_trades.json"
NARC = "files/a/1/1/2"
MSG = "files/msgdata/msg/msg_0200.json"
HEADER = "include/constants/npc_trade.h"
PERSONAL = "files/poketool/personal/personal.json"

# struct NPCTrade in include/npc_trade.h: 21 ints
FIELDS = [
    "species", "hp_iv", "atk_iv", "def_iv", "speed_iv", "spatk_iv", "spdef_iv",
    "ability", "ot_id", "cool", "beauty", "cute", "smart", "tough", "personality",
    "held_item", "ot_gender", "sheen", "language", "requested_species", "unused_flag",
]
STRUCT = struct.Struct("<21i")
IVS = ["hp", "atk", "def", "speed", "spatk", "spdef"]
CONTEST = ["cool", "beauty", "cute", "smart", "tough"]
OT_GENDERS = ["male", "female"]
NATURES = [
    "HARDY", "LONELY", "BRAVE", "ADAMANT", "NAUGHTY", "BOLD", "DOCILE", "RELAXED", "IMPISH",
    "LAX", "TIMID", "HASTY", "SERIOUS", "JOLLY", "NAIVE", "MODEST", "MILD", "QUIET",
    "BASHFUL", "RASH", "CALM", "GENTLE", "SASSY", "CAREFUL", "QUIRKY",
]


def path(rel):
    return os.path.join(ROOT, rel)


def defines(rel, prefix):
    """{NAME: value} and {value: NAME} for '#define PREFIX_X value' lines."""
    by_name, by_value = {}, {}
    for m in re.finditer(r"^#define (%s\w+)\s+(\d+|0x[0-9A-Fa-f]+)\b" % prefix,
                         open(path(rel)).read(), re.M):
        value = int(m.group(2), 0)
        by_name[m.group(1)] = value
        by_value.setdefault(value, m.group(1))
    return by_name, by_value


SPECIES, SPECIES_NAMES = defines("include/constants/species.h", "SPECIES_")
ITEMS, ITEM_NAMES = defines("include/constants/items.h", "ITEM_")
ABILITIES, ABILITY_NAMES = defines("include/constants/abilities.h", "ABILITY_")
LANGUAGES, LANGUAGE_NAMES = defines("include/config.h", "LANGUAGE_")


def lookup(table, value, what):
    if isinstance(value, int):
        return value
    if value not in table:
        sys.exit("unknown %s: %s" % (what, value))
    return table[value]


# --- NARC -------------------------------------------------------------------

def read_narc(rel):
    return read_narc_bytes(open(path(rel), "rb").read())


def read_narc_bytes(data):
    count = struct.unpack_from("<I", data, 0x18)[0]
    gmif = data.index(b"GMIF") + 8
    members = []
    for i in range(count):
        start, end = struct.unpack_from("<II", data, 0x1C + 8 * i)
        members.append(data[gmif + start:gmif + end])
    return members


def narc_bytes(members):
    """A NARC laid out like the retail one (no names; members are multiples of 4)."""
    offsets, body, pos = [], b"", 0
    for m in members:
        m = m + b"\xff" * (-len(m) % 4)
        offsets.append((pos, pos + len(m)))
        body += m
        pos += len(m)
    btaf = b"BTAF" + struct.pack("<II", 12 + 8 * len(members), len(members))
    btaf += b"".join(struct.pack("<II", s, e) for s, e in offsets)
    btnf = b"BTNF" + struct.pack("<IIHH", 0x10, 4, 0, 1)
    gmif = b"GMIF" + struct.pack("<I", 8 + len(body)) + body
    rest = btaf + btnf + gmif
    return b"NARC" + struct.pack("<HHIHH", 0xFFFE, 0x0100, 0x10 + len(rest), 0x10, 3) + rest


# --- JSON <-> binary --------------------------------------------------------

def entry_from_struct(trade_id, values, nickname, ot_name):
    v = dict(zip(FIELDS, values))
    return {
        "id": trade_id,
        "species": SPECIES_NAMES.get(v["species"], v["species"]),
        "nickname": nickname,
        "requested_species": SPECIES_NAMES.get(v["requested_species"], v["requested_species"]),
        "ivs": {s: v[s + "_iv"] for s in IVS},
        "personality": v["personality"],
        "held_item": ITEM_NAMES.get(v["held_item"], v["held_item"]),
        "ot_name": ot_name,
        "ot_id": v["ot_id"],
        "ot_gender": OT_GENDERS[v["ot_gender"]],
        "language": LANGUAGE_NAMES.get(v["language"], v["language"]),
        "contest": {s: v[s] for s in CONTEST},
        "sheen": v["sheen"],
        "ability": ABILITY_NAMES.get(v["ability"], v["ability"]),
        "unused_flag": v["unused_flag"],
    }


def struct_from_entry(e):
    v = {
        "species": lookup(SPECIES, e["species"], "species"),
        "requested_species": lookup(SPECIES, e["requested_species"], "species"),
        "personality": e["personality"],
        "held_item": lookup(ITEMS, e["held_item"], "item"),
        "ot_id": e["ot_id"],
        "ot_gender": OT_GENDERS.index(e["ot_gender"]),
        "language": lookup(LANGUAGES, e["language"], "language"),
        "sheen": e.get("sheen", 0),
        "ability": lookup(ABILITIES, e.get("ability", 0), "ability"),
        "unused_flag": e.get("unused_flag", 0),
    }
    for s in IVS:
        v[s + "_iv"] = e["ivs"][s]
    for s in CONTEST:
        v[s] = e.get("contest", {}).get(s, 0)
    return STRUCT.pack(*[to_s32(v[f]) for f in FIELDS])


def to_s32(x):
    return x - (1 << 32) if x >= 1 << 31 else x


def header_ids():
    text = open(path(HEADER)).read()
    body = re.search(r"typedef enum NpcTradeNum \{(.*?)\} NpcTradeNum;", text, re.S).group(1)
    return [i for i in re.findall(r"(NPC_TRADE_\w+)", body) if i != "NPC_TRADE_MAX"]


def header_text(ids):
    text = open(path(HEADER)).read()
    body = "".join("    %s,\n" % i for i in ids + ["NPC_TRADE_MAX"])
    return re.sub(r"(typedef enum NpcTradeNum \{\n).*?(\} NpcTradeNum;)",
                  lambda m: m.group(1) + body + m.group(2), text, flags=re.S)


def msg_text(entries):
    msg = json.load(open(path(MSG), encoding="utf-8"))
    names = [e["nickname"] for e in entries] + [e["ot_name"] for e in entries]
    msg["messages"] = [{"id": "msg_0200_%05d" % i, "en_US": n} for i, n in enumerate(names)]
    return json.dumps(msg, ensure_ascii=False, indent=2) + "\n"


def load_entries():
    entries = json.load(open(path(JSON_PATH), encoding="utf-8"))["trades"]
    for e in entries:
        for s in IVS:
            if not 0 <= e["ivs"][s] <= 31:
                sys.exit("%s: %s IV %d is not 0-31" % (e["id"], s, e["ivs"][s]))
    return entries


def outputs(entries):
    return {
        NARC: narc_bytes([struct_from_entry(e) for e in entries]),
        MSG: msg_text(entries).encode("utf-8"),
        HEADER: header_text([e["id"] for e in entries]).encode("utf-8"),
    }


# --- personality ------------------------------------------------------------

def personal():
    return json.load(open(path(PERSONAL)))["baseStats"]


def gender_ratio(species):
    frac = personal()[species]["genderRatio"]
    return int(frac * 254.75) if frac <= 1 else 255   # GENDER_RATIO() in constants/pokemon.h


def gender_of(species, pid):
    ratio = gender_ratio(species)
    if ratio == 0:
        return "male"
    if ratio == 254:
        return "female"
    if ratio == 255:
        return "genderless"
    return "female" if ratio > (pid & 0xFF) else "male"


def is_shiny(ot_id, pid):
    return ((ot_id >> 16) ^ (ot_id & 0xFFFF) ^ (pid >> 16) ^ (pid & 0xFFFF)) < 8


def describe(e):
    species = lookup(SPECIES, e["species"], "species")
    pid = e["personality"]
    abilities = personal()[species]["abilities"]
    slot = pid & 1 if abilities[1] != "ABILITY_NONE" else 0
    return {
        "nature": NATURES[pid % 25],
        "gender": gender_of(species, pid),
        "ability": "%s (slot %d)" % (abilities[slot], slot),
        "shiny": is_shiny(e["ot_id"], pid),
    }


# --- commands ---------------------------------------------------------------

def cmd_show(args):
    entries = load_entries()
    for n, e in enumerate(entries):
        if args.id and e["id"] != args.id:
            continue
        d = describe(e)
        ivs = "/".join(str(e["ivs"][s]) for s in IVS)
        print("%2d %-30s %s \"%s\" for %s" % (n, e["id"], e["species"], e["nickname"], e["requested_species"]))
        print("   OT %s (%s, id %d), %s, item %s" % (e["ot_name"], e["ot_gender"], e["ot_id"], e["language"], e["held_item"]))
        print("   IVs %s (HP/Atk/Def/Spe/SpA/SpD), personality %d: %s, %s, %s%s" % (
            ivs, e["personality"], d["nature"], d["gender"], d["ability"], ", SHINY (the game asserts against this)" if d["shiny"] else ""))


def cmd_check(args):
    ok = True
    for rel, data in outputs(load_entries()).items():
        if open(path(rel), "rb").read() != data:
            print("%s doesn't match %s: run build" % (rel, JSON_PATH))
            ok = False
    for e in load_entries():
        if describe(e)["shiny"]:
            print("%s is shiny with this personality and OT id" % e["id"])
            ok = False
    if ok:
        print("ok")
    return 0 if ok else 1


def cmd_build(args):
    for rel, data in outputs(load_entries()).items():
        if open(path(rel), "rb").read() != data:
            open(path(rel), "wb").write(data)
            print("wrote", rel)


def cmd_dump(args):
    msg = [m["en_US"] for m in json.load(open(path(MSG), encoding="utf-8"))["messages"]]
    ids = header_ids()
    entries = [entry_from_struct(i, STRUCT.unpack(m), msg[n], msg[n + len(ids)])
               for n, (i, m) in enumerate(zip(ids, read_narc(NARC)))]
    open(path(JSON_PATH), "w", encoding="utf-8").write(
        json.dumps({"trades": entries}, ensure_ascii=False, indent=4) + "\n")
    print("wrote", JSON_PATH)


def cmd_pid(args):
    species = lookup(SPECIES, args.species, "species")
    nature = NATURES.index(args.nature.replace("NATURE_", "").upper())
    abilities = personal()[species]["abilities"]
    for pid in range(1 << 16):
        if pid % 25 != nature:
            continue
        if args.gender and gender_of(species, pid) != args.gender:
            continue
        if args.ability is not None and abilities[1] != "ABILITY_NONE" and (pid & 1) != args.ability:
            continue
        if args.ot_id is not None and is_shiny(args.ot_id, pid):
            continue
        d = describe({"species": species, "personality": pid, "ot_id": args.ot_id or 0})
        print("%d  (%s, %s, %s)" % (pid, d["nature"], d["gender"], d["ability"]))
        return 0
    sys.exit("no personality value fits (is that gender possible for this species?)")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("show")
    s.add_argument("id", nargs="?")
    sub.add_parser("check")
    sub.add_parser("build")
    sub.add_parser("dump")
    s = sub.add_parser("pid")
    s.add_argument("species")
    s.add_argument("--nature", required=True)
    s.add_argument("--gender", choices=["male", "female"])
    s.add_argument("--ability", type=int, choices=[0, 1], help="ability slot (personality bit 0)")
    s.add_argument("--ot-id", type=int, help="the trade's ot_id, to avoid a shiny value")
    args = p.parse_args()
    return {"show": cmd_show, "check": cmd_check, "build": cmd_build,
            "dump": cmd_dump, "pid": cmd_pid}[args.cmd](args) or 0


if __name__ == "__main__":
    sys.exit(main())
